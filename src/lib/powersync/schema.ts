import { column, Schema, Table } from '@powersync/web'

// Trial 3: the client half of t3/powersync/sync-config.yaml, snake_case as replicated. Timestamps are ISO text,
// jsonb is JSON text, booleans are 0/1. `nid` is the integer id: PowerSync's `id` is text, and joins compare strictly.
export const appSchema = new Schema({
  areas: new Table(
    {
      created_at: column.text,
      created_by: column.integer,
      deleted_at: column.text,
      description: column.text,
      name: column.text,
      nid: column.integer,
      parent_fk: column.integer,
      region_fk: column.integer,
      type: column.text,
    },
    { indexes: { nid: ['nid'] } },
  ),
  ascents: new Table({
    created_at: column.text,
    created_by: column.integer,
    date_time: column.text,
    grade_fk: column.integer,
    nid: column.integer,
    notes: column.text,
    rating: column.integer,
    region_fk: column.integer,
    route_fk: column.integer,
    type: column.text,
  }),
  blocks: new Table(
    {
      area_fk: column.integer,
      created_at: column.text,
      created_by: column.integer,
      description: column.text,
      geolocation_fk: column.integer,
      grade_counts: column.text,
      name: column.text,
      nid: column.integer,
      order: column.integer,
      region_fk: column.integer,
    },
    { indexes: { area: ['area_fk'], nid: ['nid'] } },
  ),
  favorites: new Table({
    area_fk: column.integer,
    auth_user_fk: column.text,
    block_fk: column.integer,
    created_at: column.text,
    region_fk: column.integer,
    route_fk: column.integer,
    user_fk: column.integer,
  }),
  files: new Table({
    block_fk: column.integer,
    created_by: column.integer,
    height: column.integer,
    path: column.text,
    region_fk: column.integer,
    route_fk: column.integer,
    width: column.integer,
  }),
  geolocations: new Table(
    {
      area_fk: column.integer,
      block_fk: column.integer,
      estimated: column.integer,
      lat: column.real,
      long: column.real,
      nid: column.integer,
      region_fk: column.integer,
    },
    { indexes: { nid: ['nid'] } },
  ),
  routes: new Table({
    block_fk: column.integer,
    created_at: column.text,
    created_by: column.integer,
    description: column.text,
    first_ascent_year: column.integer,
    name: column.text,
    nid: column.integer,
    region_fk: column.integer,
    user_grade_fk: column.integer,
    user_rating: column.integer,
  }),
  routes_to_tags: new Table({ region_fk: column.integer, route_fk: column.integer, tag_fk: column.text }),
  topo_routes: new Table({
    nid: column.integer,
    path: column.text,
    region_fk: column.integer,
    route_fk: column.integer,
    top_type: column.text,
    topo_fk: column.integer,
  }),
  topos: new Table({
    block_fk: column.integer,
    file_fk: column.text,
    nid: column.integer,
    order: column.integer,
    region_fk: column.integer,
  }),
  users: new Table({ nid: column.integer, username: column.text }, { indexes: { nid: ['nid'] } }),
})
